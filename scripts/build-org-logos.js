// build-org-logos.js
// Node.js script to generate src/data/static/orgLogos.ts from counties-metadata.json


import fs from 'fs';
import path from 'path';

const countiesPath = path.resolve('public/data/geo/counties-metadata.json');
const outputPath = path.resolve('src/data/static/orgLogos.ts');
const logoDir = '/logos/';
const logoDiskDir = path.resolve('public/logos');


function toLogoFile(name) {
  // kebab-case, remove special chars, lowercased
  return (
    name
      .toLowerCase()
      .replace(/[’'`]/g, '')
      .replace(/[^a-z0-9]+/g, '')
      + '.png'
  );
}

function toKebabLogoFile(name) {
  return (
    name
      .toLowerCase()
      .replace(/[’'`]/g, '')
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-+|-+$/g, '') +
    '.png'
  );
}

const counties = JSON.parse(fs.readFileSync(countiesPath, 'utf8'));
const orgSet = new Set();

for (const county of counties) {
  // Governance
  if (county.governance?.governing_body) orgSet.add(county.governance.governing_body);
  // Primary transit agencies
  if (Array.isArray(county.primary_transit_agencies)) {
    for (const agency of county.primary_transit_agencies) {
      if (agency.name) orgSet.add(agency.name);
      if (Array.isArray(agency.alternate_names)) {
        for (const alt of agency.alternate_names) orgSet.add(alt);
      }
    }
  }
  // Advocacy groups
  const groups = county.advocacy?.groups || county.groups || [];
  for (const group of groups) {
    if (group.name) orgSet.add(group.name);
  }
}



// Gather all PNGs in the logos directory (lowercase, no extension)
const availablePngs = fs.readdirSync(logoDiskDir)
  .filter(f => f.endsWith('.png'))
  .map(f => f.toLowerCase().replace(/\.png$/, ''));

// Helper: find which logo file (if any) exists for a set of names
function findLogoForNames(names) {
  // Try all names (plain, kebab, nospace)
  const candidates = names.map(n => n.toLowerCase())
    .flatMap(n => [n, n.replace(/[^a-z0-9]/g, ''), n.replace(/[^a-z0-9]+/g, '-')]);
  const found = availablePngs.filter(png => candidates.includes(png));
  if (found.length === 1) return logoDir + found[0] + '.png';
  return null;
}

const orgLogos = {};

// First, handle transit agencies (name + alternates)
for (const county of counties) {
  if (Array.isArray(county.primary_transit_agencies)) {
    for (const agency of county.primary_transit_agencies) {
      const allNames = [agency.name, ...(agency.alternate_names || [])].filter(Boolean);
      const logo = findLogoForNames(allNames);
      for (const n of allNames) orgLogos[n] = logo;
    }
  }
}

// Add governance and advocacy groups as before, but only if not already mapped
for (const org of orgSet) {
  if (!orgLogos[org]) {
    const logo = findLogoForNames([org]);
    orgLogos[org] = logo;
  }
}

const fileContent = `// Auto-generated by build-org-logos.js\nexport const orgLogos: Record<string, string | null> = ${JSON.stringify(orgLogos, null, 2)};\n`;
fs.writeFileSync(outputPath, fileContent);
console.log('orgLogos.ts generated with', Object.keys(orgLogos).length, 'entries.');
